// Builds the report HTML file for a farmer. Returns false if farmer not found.
function write_report($conn, $farmer_id, $path) {
    $farmer = $conn->query("SELECT f.*, u.full_name FROM farmers f JOIN users u ON u.id=f.user_id WHERE f.id=$farmer_id")->fetch_assoc();
    if (!$farmer) return false;
    $scores = $conn->query("SELECT acs.*, gs.crop_type FROM agri_credit_scores acs JOIN growing_seasons gs ON gs.id=acs.season_id WHERE acs.farmer_id=$farmer_id ORDER BY acs.last_updated DESC");
    $scoreRows = []; while ($s = $scores->fetch_assoc()) $scoreRows[] = $s;
    $first = $conn->query("SELECT MIN(start_date) d FROM growing_seasons WHERE farmer_id=$farmer_id")->fetch_assoc();
    $periodStart = $first['d'] ?? date('Y-m-d');
    $periodEnd = date('Y-m-d');
    $latestScore = $scoreRows[0]['score_value'] ?? 'N/A';
    $latestTier = $scoreRows[0]['tier'] ?? 'N/A';

    $html = "<!DOCTYPE html><html><head><meta charset='utf-8'><title>AgroCredit Report - " . h($farmer['full_name']) . "</title>";
    $html .= "<style>body{font-family:Arial,sans-serif;padding:30px;color:#222} h1{color:#2E7D32} table{border-collapse:collapse;width:100%;margin-top:15px} td,th{border:1px solid #ccc;padding:8px;text-align:left}</style></head><body>";
    $html .= "<h1>MicroBoost AgroCredit Report</h1>";
    $html .= "<p><strong>Farmer:</strong> " . h($farmer['full_name']) . "<br><strong>County:</strong> " . h($farmer['county']) . "<br><strong>Primary Crop:</strong> " . h($farmer['primary_crop']) . "<br><strong>Farm Size:</strong> " . h($farmer['farm_size_acres']) . " acres</p>";
    $html .= "<p><strong>Report Period:</strong> $periodStart to $periodEnd</p>";
    $html .= "<h2>Current AgroCreditScore: $latestScore ($latestTier)</h2>";
    $html .= "<table><tr><th>Season</th><th>Score</th><th>Tier</th><th>Computed At</th></tr>";
    foreach ($scoreRows as $s) {
        $html .= "<tr><td>" . h($s['crop_type']) . "</td><td>" . h($s['score_value']) . "</td><td>" . h($s['tier']) . "</td><td>" . h($s['last_updated']) . "</td></tr>";
    }
    $html .= "</table><p style='margin-top:30px;color:#888;font-size:12px;'>Generated by MicroBoost on " . date('Y-m-d H:i:s') . " for loan officer review.</p></body></html>";
    file_put_contents($path, $html);
    return true;
}

// ---- GENERATE (Create) ----
if (isset($_GET['generate'])) {
    $farmer_id = (int)$_GET['generate'];
    $filename = "agrocredit_report_farmer{$farmer_id}_" . time() . ".html";
    if (write_report($conn, $farmer_id, __DIR__ . "/reports/$filename")) {
        $relativePath = "reports/$filename";
        $stmt = $conn->prepare("INSERT INTO agri_credit_reports (loan_officer_id, farmer_id, report_path, generated_at) VALUES (?,?,?,NOW())");
        $stmt->bind_param("iis", $officer_id, $farmer_id, $relativePath);
        $stmt->execute();
        flash_set('success', 'AgroCredit report generated.');
    } else {
        flash_set('error', 'Farmer not found.');
    }
    header("Location: lender_reports.php");
    exit();
}

// ---- REGENERATE (Update) ----
if (isset($_GET['regenerate'])) {
    $id = (int)$_GET['regenerate'];
    $r = $conn->query("SELECT * FROM agri_credit_reports WHERE id=$id AND loan_officer_id=$officer_id")->fetch_assoc();
    if ($r && write_report($conn, (int)$r['farmer_id'], __DIR__ . "/" . $r['report_path'])) {
        $conn->query("UPDATE agri_credit_reports SET generated_at=NOW() WHERE id=$id");
        flash_set('success', 'Report refreshed with the latest scores.');
    } else {
        flash_set('error', 'Report not found.');
    }
    header("Location: lender_reports.php");
    exit();
}

// ---- DELETE ----
if (isset($_GET['delete'])) {
    $id = (int)$_GET['delete'];
    $r = $conn->query("SELECT * FROM agri_credit_reports WHERE id=$id AND loan_officer_id=$officer_id")->fetch_assoc();
    if ($r) {
        $filePath = __DIR__ . "/" . $r['report_path'];
        if (file_exists($filePath)) unlink($filePath);
        $conn->query("DELETE FROM agri_credit_reports WHERE id=$id");
        flash_set('success', 'Report deleted.');
    }
    header("Location: lender_reports.php");
    exit();
}

